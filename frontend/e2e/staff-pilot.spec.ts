function authenticatorCode (secret:string, offsetSeconds = 0): string {
  const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567'
  let bits = ''
  for (const char of secret.toUpperCase()) bits += alphabet.indexOf(char).toString(2).padStart(5,'0')
  const bytes = Buffer.from(Array.from({length:Math.floor(bits.length/8)},(_,index) => parseInt(bits.slice(index*8,index*8+8),2)))
  const counter = Buffer.alloc(8); counter.writeBigUInt64BE(BigInt(Math.floor((Date.now()/1000 + offsetSeconds)/30)))
  const digest = createHmac('sha1',bytes).update(counter).digest(), offset = digest[digest.length-1]! & 15
  return ((digest.readUInt32BE(offset) & 0x7fffffff) % 1_000_000).toString().padStart(6,'0')
}

