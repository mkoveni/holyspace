import { readFileSync } from 'node:fs'
import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
const passwordFile = process.env.DIRECTORY_E2E_PASSWORD_FILE
const username = process.env.DIRECTORY_E2E_USERNAME ?? 'directory-admin'
async function signIn(page: Page) {
  await page.goto('/login')
  await page.getByPlaceholder('you@yourchurch.org').fill(username)
  await page.getByPlaceholder('••••••••').fill(readFileSync(passwordFile!, 'utf8').trim())
  await page.getByRole('button', { name: 'Sign In', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Every person. A story.' })).toBeVisible()
}
async function createPerson(page: Page, firstName: string) {
  await page.getByRole('button', { name: 'Add person', exact: true }).click()
  await page.getByLabel('First name *', { exact: true }).fill(firstName)
  await page.getByLabel('Last name *', { exact: true }).fill('Mabasa')
  await page.screenshot({ path: 'test-results/java-person-form-desktop.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Create person', exact: true }).click()
  await expect(page.getByRole('heading', { name: `${firstName} Mabasa`, exact: true })).toBeVisible()
  return page.url().split('/').at(-1)!
}
test.describe('Java directory integration', () => {
  test.skip(!passwordFile, 'Set DIRECTORY_E2E_PASSWORD_FILE for an isolated Java API administrator.')
  test('creates a person, contact, address, household, primary contact and relationship through real Java endpoints', async ({ page }) => {
    const suffix = Date.now().toString().slice(-6)
    await signIn(page)
    const personId = await createPerson(page, `Solly${suffix}`)
    await page.getByRole('button', { name: 'Add contact', exact: true }).click()
    await page.getByLabel('Email address *', { exact: true }).fill(`solly${suffix}@example.org`)
    await page.getByRole('button', { name: 'Add contact', exact: true }).last().click()
    await expect(page.getByRole('link', { name: `solly${suffix}@example.org` })).toBeVisible()
    await page.getByRole('button', { name: 'Add address', exact: true }).click()
    await page.getByLabel('Street address *', { exact: true }).fill('24 Jacaranda Avenue')
    await page.getByLabel('City *', { exact: true }).fill('Johannesburg')
    await page.getByRole('button', { name: 'Add address', exact: true }).last().click()
    await expect(page.getByText('24 Jacaranda Avenue', { exact: true })).toBeVisible()
    await page.goto('/families')
    await page.getByRole('button', { name: 'Add household', exact: true }).click()
    await page.getByLabel('Household name *').fill(`Mabasa home ${suffix}`)
    await page.screenshot({ path: 'test-results/java-household-form-desktop.png', fullPage: true, animations: 'disabled' })
    await page.getByRole('button', { name: 'Create household', exact: true }).click()
    await expect(page.getByRole('heading', { name: `Mabasa home ${suffix}` })).toBeVisible()
    const householdUrl = page.url()
    await page.getByRole('button', { name: 'Add member', exact: true }).click()
    await page.getByRole('combobox', { name: 'Person to add *', exact: true }).fill(`Solly${suffix}`)
    await page.getByRole('option', { name: `Solly${suffix} Mabasa` }).click()
    await page.getByRole('checkbox', { name: 'This is their primary household' }).check()
    await page.getByRole('button', { name: 'Add member', exact: true }).last().click()
    await expect(page.getByText('Primary household', { exact: true })).toBeVisible()
    await page.getByRole('combobox', { name: 'Household contact', exact: true }).focus()
    await page.getByRole('combobox', { name: 'Household contact', exact: true }).press('ArrowDown')
    await page.getByRole('option', { name: `Solly${suffix} Mabasa` }).click()
    await page.getByRole('button', { name: 'Save contact', exact: true }).click()
    await expect(page.getByText('Your point of contact', { exact: true })).toBeVisible()
    await page.screenshot({ path: 'test-results/java-household-desktop.png', fullPage: true, animations: 'disabled' })
    await page.goto('/people')
    const childId = await createPerson(page, `Child${suffix}`)
    await page.goto(`/people/${personId}`)
    await page.getByRole('button', { name: 'Add relationship', exact: true }).click()
    await page.getByRole('combobox', { name: 'Related person *', exact: true }).fill(`Child${suffix}`)
    await page.getByRole('option', { name: `Child${suffix} Mabasa` }).click()
    await page.getByRole('button', { name: 'Save relationship', exact: true }).click()
    await expect(page.getByRole('link', { name: `Child${suffix} Mabasa` })).toBeVisible()
    await page.screenshot({ path: 'test-results/java-person-desktop.png', fullPage: true, animations: 'disabled' })
    await page.goto(`/people/${childId}`)
    await expect(page.getByText('Child of', { exact: true })).toBeVisible()
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto(`/people/${personId}`)
    await expect(page.getByRole('heading', { name: `Solly${suffix} Mabasa` })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: 'test-results/java-person-mobile.png', fullPage: true, animations: 'disabled' })
    await page.getByRole('button', { name: 'Edit profile', exact: true }).click()
    await expect(page.getByLabel('First name *', { exact: true })).toHaveValue(`Solly${suffix}`)
    await page.screenshot({ path: 'test-results/java-person-form-mobile.png', fullPage: true, animations: 'disabled' })
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    await page.goto(householdUrl)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: 'test-results/java-household-mobile.png', fullPage: true, animations: 'disabled' })
  })
  test('rejects stale edits, explicitly reloads the latest version, and retains ended contacts and archived profiles', async ({ page, request }) => {
    await signIn(page)
    const name = `Conflict${Date.now().toString().slice(-6)}`
    const id = await createPerson(page, name)
    const token = await page.evaluate(() => localStorage.getItem('holyspace.java.auth.token'))
    const headers = { Authorization: `Bearer ${token}` }
    await page.getByRole('button', { name: 'Edit profile', exact: true }).click()
    const profile = await (await request.get(`/api/people/${id}`, { headers })).json()
    const updated = await request.put(`/api/people/${id}`, { headers, data: { expectedVersion: profile.version, person: { ...profile.details, firstName: `${name}Latest` }, membershipType: 'ACTIVE_MEMBER' } })
    expect(updated.status()).toBe(204)
    await page.getByLabel('First name *', { exact: true }).fill('Stale draft')
    await page.getByRole('button', { name: 'Save changes', exact: true }).click()
    await expect(page.getByRole('alert').filter({ hasText: 'These details have changed' })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Save changes', exact: true })).toBeDisabled()
    await page.getByRole('button', { name: 'Reload latest details', exact: true }).click()
    await expect(page.getByLabel('First name *', { exact: true })).toHaveValue(`${name}Latest`)
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    await page.reload()
    await page.getByRole('button', { name: 'Add contact', exact: true }).click()
    await page.getByLabel('Email address *', { exact: true }).fill('history@example.org')
    await page.getByRole('button', { name: 'Add contact', exact: true }).last().click()
    await page.getByRole('button', { name: 'End contact history@example.org', exact: true }).click()
    await page.getByRole('button', { name: 'End now', exact: true }).click()
    await page.getByRole('tab', { name: 'History', exact: true }).click()
    await expect(page.getByText('history@example.org', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Archive person', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Archive person', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Restore person', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Restore person', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Restore person', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Archive person', exact: true })).toBeVisible()
  })
})
